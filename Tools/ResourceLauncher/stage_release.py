"""Assemble a new code-only Unity checkout. Never mutates or deletes source data."""
from pathlib import Path
import hashlib,json,shutil,sys
SOURCE_SUFFIXES={'.cs','.c','.cpp','.mm','.m','.h','.asmdef','.asmref'}
PLUGIN_BINARIES={
 'Assets/Plugins/iOS/libslua.a','Assets/Plugins/iOS/libmp3lame.a',
 'Assets/Plugins/Slua_Managed/BytesHelper.dll','Assets/Plugins/ICSharpCode.SharpZipLib.dll','Assets/Plugins/Ionic.Zip.dll',
 'Assets/Plugins/x86_64/slua.dll','Assets/Plugins/x86/slua.dll','Assets/Plugins/x86/slua.so','Assets/Plugins/x64/slua.so','Assets/Plugins/x64/slua.dll',
 'Assets/Plugins/x86_64/ConvexDecompositionDll.dll','Assets/Plugins/x86/ConvexDecompositionDll.dll'}
PLUGIN_BINARIES.update({'Assets/I18N'+suffix+'.dll' for suffix in ['', '.CJK','.MidEast','.Other','.Rare','.West']})
PLUGIN_BINARIES.update({'Assets/ThirdParty/DOTween/'+name+'.dll' for name in ['DOTween','DOTween43','DOTween46','DOTween50']})
PLUGIN_BINARIES.add('Assets/ThirdParty/DOTween/Editor/DOTweenEditor.dll')
CONFIG={'Assets/LauncherArt/app-icon.png','Assets/LauncherArt/Fonts/NotoSerifCJKsc-Regular.otf','Assets/LauncherArt/Fonts/MaShanZheng-Regular.ttf','Assets/LauncherArt/Fonts/Noto-OFL.txt','Assets/LauncherArt/Fonts/MaShanZheng-OFL.txt','Assets/PortPreparation/Launcher/Preservation/link.xml','Assets/mcs.rsp','Assets/link.xml','Assets/Meteor/TrueSync/link.xml','Assets/PortPreparation/link.xml'}
def allowed(path):
 p=path.as_posix()
 return p.startswith('Assets/') and (path.suffix in SOURCE_SUFFIXES or p in PLUGIN_BINARIES or p in CONFIG or p == 'Assets/LauncherArt/volcanic-night.png')
def stage(source,target):
 source=source.resolve();target=target.absolute()
 if target==source or source in target.parents or target in source.parents:raise ValueError('Isolated output required')
 if target.exists():raise FileExistsError(target)
 if not (source/'Assets').is_dir():raise ValueError('Unity source missing')
 target.mkdir(parents=True)
 inventory=[]
 for f in sorted((source/'Assets').rglob('*')):
  if not f.is_file():continue
  relative=f.relative_to(source)
  if not allowed(relative):continue
  if f.is_symlink() or any(p.is_symlink() for p in f.parents if p!=source.parent):raise ValueError('Source links disallowed')
  out=target/relative;out.parent.mkdir(parents=True,exist_ok=True);shutil.copy2(f,out)
  meta=Path(str(f)+'.meta')
  if meta.exists():shutil.copy2(meta,Path(str(out)+'.meta'))
  inventory.append({'path':str(relative),'sha256':hashlib.sha256(f.read_bytes()).hexdigest(),'bytes':f.stat().st_size})
 for name in ['ProjectSettings']:
  if (source/name).exists():shutil.copytree(source/name,target/name,symlinks=False)
 packages=target/'Packages';packages.mkdir(exist_ok=True)
 for name in ['manifest.json','packages-lock.json']:
  p=source/'Packages'/name
  if p.exists():shutil.copy2(p,packages/name)
 # Scene is generated by exact Unity in this staging checkout, never copied from the game.
 settings=target/'ProjectSettings/EditorBuildSettings.asset'
 settings.parent.mkdir(exist_ok=True)
 settings.write_text('%YAML 1.1\n%TAG !u! tag:unity3d.com,2011:\n--- !u!1045 &1\nEditorBuildSettings:\n  m_ObjectHideFlags: 0\n  serializedVersion: 2\n  m_Scenes: []\n  m_configObjects: {}\n')
 (target/'resource-free-source-inventory.json').write_text(json.dumps(inventory,ensure_ascii=False,indent=2))
 return inventory
if __name__=='__main__':
 if len(sys.argv)!=3:raise SystemExit('usage: stage_release.py SOURCE NEW_STAGE')
 print(json.dumps({'approved_files':len(stage(Path(sys.argv[1]),Path(sys.argv[2]))),'stage':sys.argv[2]}))
